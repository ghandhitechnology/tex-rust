"""Build engine/src/rt/fast_macro_gen.rs: the generated macro_call (gen/*.rs, emitted as
`macrocall_full` because externs.FAST_PATHS lists it) with the §399 group-copying loop
replaced by Globals::scan_group_fast (rt/fast_macro.rs). Run after tools/w2rs/emit.py.

Usage: python -I tools/gen_fast_macro.py
"""
import pathlib
import re

PORT = pathlib.Path(__file__).resolve().parents[1]
GEN = PORT / "engine" / "src" / "gen"
OUT = PORT / "engine" / "src" / "rt" / "fast_macro_gen.rs"


def extract(name):
    for f in sorted(GEN.glob("*.rs")):
        lines = f.read_text(encoding="utf-8").split("\n")
        for i, l in enumerate(lines):
            if l.startswith(f"    pub fn {name}(&mut self"):
                j = i
                while lines[j] != "    }":
                    j += 1
                return lines[i:j + 1]
    raise SystemExit(f"{name} not found in {GEN}")


def main():
    fn = extract("macrocall_full")
    fn[0] = fn[0].replace("macrocall_full", "macrocall")
    start = next(i for i, l in enumerate(fn) if l.strip() == "'bs6_1: {")
    end = next(i for i in range(start, len(fn)) if fn[i].strip() == "rbraceptr = p;") - 1
    assert fn[end].strip() == "}", fn[end]
    block = fn[start:end + 1]
    body = "\n".join(l.strip() for l in block)
    # the loop being replaced, statement by statement (fails loudly if the translator's
    # output for §399 ever changes)
    expected = [
        "unbalance = 1;", "while true {", "q = self.avail;", "if (q == (-268435455)) {",
        "q = self.getavail();", "} else {", "self.avail = (*ix(self.mem, q)).hh_rh();",
        "(*ix(self.mem, q)).set_hh_rh((-268435455));", "self.dynused += 1;", "}",
        "(*ix(self.mem, p)).set_hh_rh(q);", "(*ix(self.mem, q)).set_hh_lh(self.curtok);", "p = q;",
        "self.gettoken();", "if (self.curtok == self.partoken) {", "if (((self.longstate) as i32) != 115) {",
    ]
    got = [l.strip() for l in block[1:1 + len(expected)]]
    assert got == expected, "\n".join(f"{a!r} vs {b!r}" for a, b in zip(got, expected) if a != b)
    tail = [l.strip() for l in block[-14:]]
    assert tail == ["}", "}", "if (self.curtok < 768) {", "if (self.curtok < 512) {", "unbalance += 1;",
                    "} else {", "unbalance -= 1;", "if (unbalance == 0) {", "break 'bs6_1;", "}", "}", "}",
                    "}", "}"], tail
    # the runaway report: everything inside `if longstate <> long_call then`, up to the
    # `goto exit` (break 'bs1_1)
    k = 1 + len(expected)
    stop = next(i for i in range(k, len(block)) if block[i].strip() == "break 'bs1_1;")
    error_path = block[k:stop + 1]
    ind = block[0][:len(block[0]) - len(block[0].lstrip())]
    new = [ind + "'bs6_1: {",
           ind + "    if self.scan_group_fast(&mut p, &mut unbalance) {",
           ind + "        break 'bs6_1;",
           ind + "    }",
           ind + "    // a \\par token ended the group in a macro that is not \\long (tex.web §396)",
           *error_path,
           ind + "}"]
    fn = fn[:start] + new + fn[end + 1:]
    # parameter list bookkeeping for end_token_list's O(1) flush (rt/fast_macro.rs
    # flush_param): count the nodes appended to the parameter being built, and record
    # (tail, length) when it is tucked away in pstack and when it moves to param_stack
    out, seen = [], {"append": 0, "start": 0, "stripped": 0, "plain": 0, "copy": 0}
    for l in fn:
        st = l.strip()
        ind = l[:len(l) - len(l.lstrip())]
        out.append(l)
        if st == "p = q;":
            out.append(ind + "self.rt.pcount += 1;")
            seen["append"] += 1
        elif st == "p = (self.memtop - 3);":
            out.append(ind + "self.rt.pcount = 0;")
            seen["start"] += 1
        elif st == "(*ix(self.pstack, ((n) as i32))) = (*ix(self.mem, p)).hh_rh();":
            # braces stripped: the list runs from after the left brace to rbrace_ptr
            out.append(ind + "self.rt.pstack_meta[n as usize] = (rbraceptr, self.rt.pcount - 2);")
            seen["stripped"] += 1
        elif (st == "(*ix(self.pstack, ((n) as i32))) = (*ix(self.mem, (self.memtop - 3))).hh_rh();"
              and seen["stripped"] and not seen["plain"]):
            out.append(ind + "self.rt.pstack_meta[n as usize] = (p, self.rt.pcount);")
            seen["plain"] += 1
        elif st == "(*ix(self.paramstack, (self.paramptr + m))) = (*ix(self.pstack, m));":
            out.append(ind + "{ let __m = self.rt.pstack_meta[m as usize]; self.set_pmeta(self.paramptr + m, __m); }")
            seen["copy"] += 1
    assert seen == {"append": 3, "start": 1, "stripped": 1, "plain": 1, "copy": 1}, seen
    fn = out
    text = ("//! GENERATED by tools/gen_fast_macro.py from the translator's macro_call\n"
            "//! (gen/*.rs macrocall_full) with tex.web §399 replaced by scan_group_fast\n"
            "//! (rt/fast_macro.rs). Do not edit.\n"
            "#![allow(unused_assignments, unused_mut, unused_parens, unused_variables, clippy::all)]\n\n"
            "use super::*;\nuse crate::gen::globals::Globals;\n\nimpl Globals {\n"
            + "\n".join(fn) + "\n}\n")
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(fn)} lines)")


if __name__ == "__main__":
    main()
