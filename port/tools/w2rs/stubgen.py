"""List the external routines the generated engine calls, with Rust signatures.
Prints a Rust `impl Globals` block of todo!() stubs for those not yet implemented by hand
(names found as `fn <name>(` anywhere under engine/src/rt are skipped)."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import externs  # noqa: E402

RT = {("int", "i32"): "i32", ("bool",): "bool", ("real",): "f64", ("ptr", ("int", "u8")): "Ptr<u8>",
      ("str",): "&[u8]", ("file", None): "FileRef", ("int", "i64"): "i64", ("int", "u8"): "u8"}

gen_dir, rt_dir = sys.argv[1], sys.argv[2]
code = "".join(open(os.path.join(gen_dir, f), encoding="utf-8").read() for f in os.listdir(gen_dir) if f.endswith(".rs"))
have = set()
for root, _, files in os.walk(rt_dir):
    for f in files:
        if f.endswith(".rs") and f != "stubs.rs":
            have |= set(re.findall(r"\bfn (\w+)\s*[<(]", open(os.path.join(root, f), encoding="utf-8").read()))

out = ["// Stubs for externals not yet ported. Generated by tools/w2rs/stubgen.py.",
       "#![allow(unused_variables)]", "use super::*;", "use crate::gen::globals::Globals;", "", "impl Globals {"]
for name, (ret, params) in sorted(externs.FUNCS.items()):
    if f"self.{name}(" not in code or name in have:
        continue
    ps = ", ".join(f"a{i}: {RT[p]}" for i, p in enumerate(params))
    out.append(f"    pub fn {name}(&mut self{', ' if ps else ''}{ps}) -> {RT[ret]} {{ todo!(\"{name}\") }}")
for name, params in sorted(externs.PROCS.items()):
    if f"self.{name}(" not in code or name in have:
        continue
    ps = ", ".join(f"a{i}: {RT[p]}" for i, p in enumerate(params))
    out.append(f"    pub fn {name}(&mut self{', ' if ps else ''}{ps}) {{ todo!(\"{name}\") }}")
out.append("}")
print("\n".join(out))
