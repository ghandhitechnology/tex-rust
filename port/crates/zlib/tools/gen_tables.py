"""Generate src/tables.rs from zlib 1.3.2's trees.h and inffixed.h.

Usage: python -I tools/gen_tables.py <zlib-src-dir> > src/tables.rs
The tables are copied verbatim (not recomputed) so they match the C build.
"""
import re
import sys

src = sys.argv[1]
trees = open(f"{src}/trees.h", encoding="ascii").read()
fixed = open(f"{src}/inffixed.h", encoding="ascii").read()


def body(text, name):
    m = re.search(re.escape(name) + r"[^=]*=\s*\{(.*?)\};", text, re.S)
    if not m:
        raise SystemExit(f"table {name} not found")
    return m.group(1)


def ints(s):
    return [int(x) for x in re.findall(r"-?\d+", s)]


out = []
w = out.append
w("// Generated by tools/gen_tables.py from zlib 1.3.2 trees.h and inffixed.h.")
w("// Do not edit by hand.")
w("")
w("use crate::inftrees::Code;")
w("use crate::trees::CtData;")
w("")


def ct_table(name, rust, n):
    vals = ints(body(trees, name))
    assert len(vals) == 2 * n, (name, len(vals))
    w(f"pub(crate) static {rust}: [CtData; {n}] = [")
    for i in range(0, len(vals), 2):
        w(f"    CtData {{ fc: {vals[i]}, dl: {vals[i + 1]} }},")
    w("];")
    w("")


def byte_table(name, rust, n, ty="u8"):
    vals = ints(body(trees, name))
    assert len(vals) == n, (name, len(vals))
    w(f"pub(crate) static {rust}: [{ty}; {n}] = [")
    for i in range(0, n, 16):
        w("    " + ", ".join(str(v) for v in vals[i:i + 16]) + ",")
    w("];")
    w("")


ct_table("static_ltree", "STATIC_LTREE", 288)
ct_table("static_dtree", "STATIC_DTREE", 30)
byte_table("_dist_code", "DIST_CODE", 512)
byte_table("_length_code", "LENGTH_CODE", 256)
byte_table("base_length", "BASE_LENGTH", 29, "i32")
byte_table("base_dist", "BASE_DIST", 30, "i32")


def code_table(name, rust, n):
    vals = ints(body(fixed, name))
    assert len(vals) == 3 * n, (name, len(vals))
    w(f"pub(crate) static {rust}: [Code; {n}] = [")
    for i in range(0, len(vals), 3):
        w(f"    Code {{ op: {vals[i]}, bits: {vals[i + 1]}, val: {vals[i + 2]} }},")
    w("];")
    w("")


code_table("lenfix", "LENFIX", 512)
code_table("distfix", "DISTFIX", 32)
sys.stdout.write("\n".join(out))
